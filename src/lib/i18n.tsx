export type Locale = "fr" | "en";
const LocaleContext = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: Key) => string;
}>({ locale: "fr", setLocale: () => {}, t: (key) => fr[key] });
export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try {
      return localStorage.getItem("renvodesk-locale") === "en" ? "en" : "fr";
    } catch {
      return "fr";
    }
  });
  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      localStorage.setItem("renvodesk-locale", locale);
    } catch {
      /* Storage may be unavailable. */
    }
  }, [locale]);
  return (
    <LocaleContext.Provider
      value={{
        locale,
        setLocale,
        t: (key) => (locale === "fr" ? fr : en)[key],
      }}
    >
      {children}
    </LocaleContext.Provider>
  );
}
export function useLocale() {
  return useContext(LocaleContext);
}
export function formatMoney(cents: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "fr" ? "fr-BE" : "en-IE", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: 2,
    minimumFractionDigits: 0,
  }).format(cents / 100);
}
